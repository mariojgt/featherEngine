import type { SceneObjectKind, Vector3Tuple } from '../types/common';

export type SimpleInteractionTriggerType =
  | 'interact'
  | 'collision'
  | 'trigger-enter'
  | 'trigger-exit'
  | 'start'
  | 'timer'
  | 'health-zero';

export type SimpleInteractionActionType =
  | 'move'
  | 'rotate'
  | 'scale'
  | 'destroy'
  | 'damage'
  | 'score'
  | 'play-animation'
  | 'play-sound'
  | 'spawn'
  | 'event';

export interface SimpleInteractionTrigger {
  type: SimpleInteractionTriggerType;
  /** Repeating interval for timer triggers. */
  seconds?: number;
}

export interface SimpleInteractionAction {
  type: SimpleInteractionActionType;
  /** Target position/rotation/scale for transform actions. */
  vector?: Vector3Tuple;
  /** Damage or score amount. */
  value?: number;
  assetId?: string;
  animationId?: string;
  eventName?: string;
  spawnKind?: SceneObjectKind;
}

/**
 * Beginner-authored rule. This metadata is only an editor representation: execution always comes
 * from the normal Blueprint graph generated by {@link compileSimpleInteractionBlock}.
 */
export interface SimpleInteraction {
  id: string;
  trigger: SimpleInteractionTrigger;
  action: SimpleInteractionAction;
  duration?: number;
  then?: SimpleInteractionAction[];
  params?: Record<string, unknown>;
}

export type SimpleInteractionDraft = Omit<SimpleInteraction, 'id'>;

